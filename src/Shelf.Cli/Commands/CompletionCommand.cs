using System.CommandLine;
using System.CommandLine.Completions;
using System.Text;
using System.Text.RegularExpressions;

namespace Shelf.Cli.Commands;

/// <summary>
/// <c>shelf completion bash|zsh|fish</c> (PRD 7.1): a completion script on standard output. The framework has no generator
/// (ADR 0002), so the scripts are written from the command model: every command, subcommand and option that the parser knows
/// is in them, and a new command needs nothing more. Nothing is evaluated at completion time (no process is started), so
/// the scripts stay fast and need no AOT-sensitive code.
/// </summary>
internal static partial class CompletionCommand
{
    private static readonly string[] Shells = ["bash", "zsh", "fish"];

    /// <summary>The option whose value is a path of the file system.</summary>
    private const string PathOption = "--library";

    public static Command Create(Command root, TextWriter stdout)
    {
        var shell = new Argument<string>("shell") { Description = "bash, zsh or fish" };
        shell.AcceptOnlyFromAmong(Shells);
        var command = new Command("completion", "Print a completion script for bash, zsh or fish");
        command.Arguments.Add(shell);
        command.SetAction(parseResult =>
        {
            var model = Node.Of(root, [], inherited: []);
            var script = parseResult.GetValue(shell) switch
            {
                "bash" => Bash(model),
                "zsh" => Zsh(model),
                _ => Fish(model),
            };
            stdout.Write(script);
            return ExitCodes.Success;
        });
        return command;
    }

    /// <summary>A command with what can be typed after it. <c>Words</c> are the subcommands and the values of its argument.</summary>
    private sealed record Node(string[] Path, List<Item> Options, List<Item> Words, List<Node> Subcommands)
    {
        public string Key => string.Join(' ', Path);

        public static Node Of(Command command, string[] path, List<Item> inherited)
        {
            var options = new List<Item>(inherited);
            var own = command.Options.Where(o => !o.Hidden).ToList();
            options.AddRange(own.Select(Item.Of).Where(i => i.Names.Length > 0));

            // A recursive option is valid below the command, too.
            var passed = new List<Item>(inherited);
            passed.AddRange(own.Where(o => o.Recursive).Select(Item.Of).Where(i => i.Names.Length > 0));

            var subcommands = command.Subcommands.Where(c => !c.Hidden).OrderBy(c => c.Name, StringComparer.Ordinal).ToList();
            var children = subcommands.Select(c => Of(c, [.. path, c.Name], passed)).ToList();
            var words = subcommands.Select(c => new Item([c.Name], c.Description ?? string.Empty, Value: false)).ToList();
            foreach (var argument in command.Arguments)
            {
                // The values a command lists for its argument (AcceptOnlyFromAmong) are words, too.
                foreach (var value in argument.GetCompletions(CompletionContext.Empty))
                {
                    words.Add(new Item([value.Label], argument.Description ?? string.Empty, Value: false));
                }
            }

            return new Node(path, options, words, children);
        }

        public IEnumerable<Node> All() => new[] { this }.Concat(Subcommands.SelectMany(s => s.All()));
    }

    /// <summary>An option (with its aliases) or a word.</summary>
    private sealed record Item(string[] Names, string Description, bool Value)
    {
        public static Item Of(Option option) => new(
            [.. new[] { option.Name }.Concat(option.Aliases).Where(n => NameShape().IsMatch(n)).OrderByDescending(n => n.StartsWith("--", StringComparison.Ordinal)).ThenBy(n => n, StringComparer.Ordinal)],
            option.Description ?? string.Empty,
            option.Arity.MaximumNumberOfValues > 0);

        public string Long => Names.FirstOrDefault(n => n.StartsWith("--", StringComparison.Ordinal)) ?? Names[0];
    }

    [GeneratedRegex("^--?[A-Za-z][A-Za-z0-9-]*$")]
    private static partial Regex NameShape();

    // ---- bash ----

    private static string Bash(Node model)
    {
        var text = new StringBuilder();
        text.Append("# bash completion for shelf (generated by \"shelf completion bash\")\n");
        text.Append("# Usage: source <(shelf completion bash)\n");
        text.Append("_shelf() {\n");
        text.Append("  local cur=\"${COMP_WORDS[COMP_CWORD]}\" prev=\"\" path=\"\" w i subs opts\n");
        text.Append("  if [ \"$COMP_CWORD\" -gt 0 ]; then prev=\"${COMP_WORDS[COMP_CWORD-1]}\"; fi\n");
        text.Append("  for ((i = 1; i < COMP_CWORD; i++)); do\n");
        text.Append("    w=\"${COMP_WORDS[i]}\"\n");
        text.Append("    case \"$path|$w\" in\n");
        foreach (var node in model.All().Where(n => n.Path.Length > 0))
        {
            var parent = string.Join(' ', node.Path[..^1]);
            text.Append($"      \"{parent}|{node.Path[^1]}\") path=\"{node.Key}\" ;;\n");
        }

        text.Append("    esac\n");
        text.Append("  done\n");
        text.Append($"  if [ \"$prev\" = \"{PathOption}\" ]; then\n");
        text.Append("    compopt -o filenames 2>/dev/null\n");
        text.Append("    COMPREPLY=($(compgen -f -- \"$cur\"))\n");
        text.Append("    return\n");
        text.Append("  fi\n");
        text.Append("  case \"$path\" in\n");
        foreach (var node in model.All())
        {
            text.Append($"    \"{node.Key}\") subs=\"{string.Join(' ', node.Words.Select(w => w.Names[0]))}\"; opts=\"{string.Join(' ', node.Options.SelectMany(o => o.Names).Order(StringComparer.Ordinal))}\" ;;\n");
        }

        text.Append("  esac\n");
        text.Append("  if [[ \"$cur\" == -* ]]; then\n");
        text.Append("    COMPREPLY=($(compgen -W \"$opts\" -- \"$cur\"))\n");
        text.Append("  else\n");
        text.Append("    COMPREPLY=($(compgen -W \"$subs\" -- \"$cur\"))\n");
        text.Append("  fi\n");
        text.Append("}\n");
        text.Append("complete -F _shelf shelf\n");
        return text.ToString();
    }

    // ---- zsh ----

    private static string Zsh(Node model)
    {
        var text = new StringBuilder();
        text.Append("#compdef shelf\n");
        text.Append("# zsh completion for shelf (generated by \"shelf completion zsh\")\n");
        text.Append("# Usage: shelf completion zsh > \"${fpath[1]}/_shelf\"   (or: source <(shelf completion zsh) after compinit)\n");
        text.Append("_shelf() {\n");
        text.Append("  local path=\"\" w i\n");
        text.Append("  local -a subs opts\n");
        text.Append("  for ((i = 2; i < CURRENT; i++)); do\n");
        text.Append("    w=\"${words[i]}\"\n");
        text.Append("    case \"$path|$w\" in\n");
        foreach (var node in model.All().Where(n => n.Path.Length > 0))
        {
            var parent = string.Join(' ', node.Path[..^1]);
            text.Append($"      \"{parent}|{node.Path[^1]}\") path=\"{node.Key}\" ;;\n");
        }

        text.Append("    esac\n");
        text.Append("  done\n");
        text.Append($"  if [[ \"${{words[CURRENT-1]}}\" == {PathOption} ]]; then\n");
        text.Append("    _files\n");
        text.Append("    return\n");
        text.Append("  fi\n");
        text.Append("  case \"$path\" in\n");
        foreach (var node in model.All())
        {
            text.Append($"    \"{node.Key}\")\n");
            text.Append($"      subs=({string.Join(' ', node.Words.Select(w => ZshEntry(w.Names[0], w.Description)))})\n");
            text.Append($"      opts=({string.Join(' ', node.Options.SelectMany(o => o.Names.Select(n => ZshEntry(n, o.Description))).OrderBy(e => e, StringComparer.Ordinal))})\n");
            text.Append("      ;;\n");
        }

        text.Append("  esac\n");
        text.Append("  if [[ \"$PREFIX\" == -* ]]; then\n");
        text.Append("    _describe -t options 'option' opts\n");
        text.Append("  elif (( ${#subs} )); then\n");
        text.Append("    _describe -t commands 'command' subs\n");
        text.Append("  fi\n");
        text.Append("}\n");
        text.Append("if [ \"$funcstack[1]\" = \"_shelf\" ]; then\n");
        text.Append("  _shelf \"$@\"\n");
        text.Append("else\n");
        text.Append("  compdef _shelf shelf\n");
        text.Append("fi\n");
        return text.ToString();
    }

    /// <summary>One element of an array for <c>_describe</c>: <c>name:description</c>, in single quotes.</summary>
    private static string ZshEntry(string name, string description)
    {
        var entry = name.Replace(":", "\\:", StringComparison.Ordinal) + ":" + description.ReplaceLineEndings(" ");
        return "'" + entry.Replace("'", "'\\''", StringComparison.Ordinal) + "'";
    }

    // ---- fish ----

    private static string Fish(Node model)
    {
        var text = new StringBuilder();
        text.Append("# fish completion for shelf (generated by \"shelf completion fish\")\n");
        text.Append("# Usage: shelf completion fish > ~/.config/fish/completions/shelf.fish\n");
        text.Append("complete -c shelf -f\n");
        foreach (var node in model.All())
        {
            var seen = string.Join("; and ", node.Path.Select(p => $"__fish_seen_subcommand_from {p}"));
            var siblings = string.Join(' ', node.Words.Select(w => w.Names[0]));
            var wordCondition = node.Path.Length == 0 ? "__fish_use_subcommand" : $"{seen}; and not __fish_seen_subcommand_from {siblings}";
            foreach (var word in node.Words)
            {
                text.Append($"complete -c shelf -n {FishQuote(wordCondition)} -a {FishQuote(word.Names[0])} -d {FishQuote(word.Description)}\n");
            }

            // The options of the root are valid everywhere (they are the recursive ones, and the framework's own).
            foreach (var option in node.Options.Where(o => node.Path.Length == 0 || !model.Options.Any(r => r.Long == o.Long)))
            {
                var flags = string.Join(' ', option.Names.Select(n => n.StartsWith("--", StringComparison.Ordinal) ? $"-l {n[2..]}" : $"-s {n[1..]}"));
                var argument = !option.Value ? string.Empty : option.Long == PathOption ? " -r -F" : " -r";
                var condition = node.Path.Length == 0 ? string.Empty : $" -n {FishQuote(seen)}";
                text.Append($"complete -c shelf{condition} {flags}{argument} -d {FishQuote(option.Description)}\n");
            }
        }

        return text.ToString();
    }

    private static string FishQuote(string text) =>
        "'" + text.ReplaceLineEndings(" ").Replace("\\", "\\\\", StringComparison.Ordinal).Replace("'", "\\'", StringComparison.Ordinal) + "'";
}
